#!/usr/bin/env python3
"""gen_fsr2_shaders.py GLSLC SPIRV_CROSS FSR2_DIR OUT.cpp

FSR 2.2's compute passes (third_party/fsr2/shaders) compiled for rvk's use of it (rvk/fsr2.cpp) - in place of AMD's
FidelityFX_SC.exe, a Windows tool, and its ffx_fsr2_shaders_vk.cpp: the SPIR-V of each pass and the permutations rvk
can ask for, each with its resources' names and bindings (the backend binds by name), and
fsr2GetPermutationBlobByIndexVK, which the Vulkan backend (third_party/fsr2/vk/ffx_fsr2_vk.cpp) calls.

The options rvk fixes are compiled in: colour in LDR (the tone mapped scene), motion vectors at the render resolution
and without the jitter, depth not inverted; and no half-precision variants (rvk's device doesn't enable 16-bit
floats; the FP16 option is answered with the 32-bit blob). What varies: the reprojection's Lanczos (by the GPU's wave
size) and the accumulate pass's sharpening.
"""
import json
import pathlib
import subprocess
import sys
import tempfile

glslc, spirv_cross, fsr2, out = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3]), pathlib.Path(sys.argv[4])

BASE = ['-DFFX_GPU=1', '-DFFX_GLSL=1', '-DFFX_HALF=0',
        '-DFFX_FSR2_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0', '-DFFX_FSR2_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0',
        '-DFFX_FSR2_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1', '-DFFX_FSR2_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0',
        '-DFFX_FSR2_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2',
        '-DFFX_FSR2_OPTION_HDR_COLOR_INPUT=0', '-DFFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1',
        '-DFFX_FSR2_OPTION_JITTERED_MOTION_VECTORS=0', '-DFFX_FSR2_OPTION_INVERTED_DEPTH=0']

# FfxFsr2Pass -> its shader; whether its sharpening option matters (the accumulate pass only).
PASSES = [('FFX_FSR2_PASS_DEPTH_CLIP', 'ffx_fsr2_depth_clip_pass', False),
          ('FFX_FSR2_PASS_RECONSTRUCT_PREVIOUS_DEPTH', 'ffx_fsr2_reconstruct_previous_depth_pass', False),
          ('FFX_FSR2_PASS_LOCK', 'ffx_fsr2_lock_pass', False),
          ('FFX_FSR2_PASS_ACCUMULATE', 'ffx_fsr2_accumulate_pass', False),
          ('FFX_FSR2_PASS_ACCUMULATE_SHARPEN', 'ffx_fsr2_accumulate_pass', True),
          ('FFX_FSR2_PASS_RCAS', 'ffx_fsr2_rcas_pass', False),
          ('FFX_FSR2_PASS_COMPUTE_LUMINANCE_PYRAMID', 'ffx_fsr2_compute_luminance_pyramid_pass', False),
          ('FFX_FSR2_PASS_GENERATE_REACTIVE', 'ffx_fsr2_autogen_reactive_pass', False),
          ('FFX_FSR2_PASS_TCR_AUTOGENERATE', 'ffx_fsr2_tcr_autogen_pass', False)]


def compile_pass(src, defines, opt, tmp):
    spv = tmp / f'{src.stem}{"".join(d[-1] for d in defines)}{opt}.spv'
    subprocess.run([glslc, '-fshader-stage=comp', '--target-env=vulkan1.1', opt, *BASE, *defines,
                    f'-I{fsr2 / "shaders"}', str(src), '-o', str(spv)], check=True)
    return spv


def reflect(spv):
    js = spv.with_suffix('.json')
    subprocess.run([spirv_cross, str(spv), '--reflect', '--output', str(js)], check=True)
    j = json.loads(js.read_text())
    kinds = {'images': 'storage', 'separate_images': 'sampled', 'ubos': 'uniform'}
    return {kinds[k]: [(r['name'], r['binding']) for r in j.get(k, []) if r.get('set') == 1] for k in kinds}


def blob(name, spv_path, names_by_binding, optimised):
    words = spv_path.read_bytes()
    text = [f'const uint8_t {name}_data[] = {{']
    for i in range(0, len(words), 24):
        text.append('    ' + ', '.join(str(b) for b in words[i:i + 24]) + ',')
    text.append('};')
    fields = []
    for kind in ('storage', 'sampled', 'uniform'):
        binds = sorted(b for _, b in optimised[kind])
        names = []
        for b in binds:
            n = names_by_binding[kind][b]
            names.append(n[:-2] if kind == 'uniform' and n.endswith('_t') else n)   # (the block's instance name)
        arr = f'{name}_{kind}'
        if binds:
            text.append(f'const char* {arr}_names[] = {{{", ".join(chr(34) + n + chr(34) for n in names)}}};')
            text.append(f'const uint32_t {arr}_bindings[] = {{{", ".join(str(b) for b in binds)}}};')
            fields.append((len(binds), f'{arr}_names', f'{arr}_bindings'))
        else:
            fields.append((0, 'nullptr', 'nullptr'))
    (ns, nsn, nsb), (nm, nmn, nmb), (nu, nun, nub) = fields
    text.append(f'const Fsr2ShaderBlobVK {name} = {{{name}_data, uint32_t(sizeof({name}_data)), {ns}, {nm}, {nu}, '
                f'{nsn}, {nsb}, {nmn}, {nmb}, {nun}, {nub}}};')
    return '\n'.join(text)


def main():
    parts = ['// Generated by tools/gen_fsr2_shaders.py - do not edit.',
             '#include "vk/shaders/ffx_fsr2_shaders_vk.h"', '', 'namespace {', '']
    table = []
    with tempfile.TemporaryDirectory() as t:
        tmp = pathlib.Path(t)
        for pass_id, shader, sharpen in PASSES:
            src = fsr2 / 'shaders' / f'{shader}.glsl'
            row = []
            for lanczos in (0, 1):
                defines = [f'-DFFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE={lanczos}',
                           f'-DFFX_FSR2_OPTION_APPLY_SHARPENING={int(sharpen)}']
                plain = reflect(compile_pass(src, defines, '-O0', tmp))
                names = {k: {b: n for n, b in v} for k, v in plain.items()}
                spv = compile_pass(src, defines, '-Os', tmp)
                name = f'k{pass_id.title().replace("_", "")}{lanczos}'
                parts.append(blob(name, spv, names, reflect(spv)))
                parts.append('')
                row.append(name)
            table.append((pass_id, row))
    parts.append('}  // namespace')
    parts.append('')
    parts.append('// The blob for a pass and the backend\'s permutation options (ffx_fsr2_shaders_vk.h): only the Lanczos bit')
    parts.append('// chooses; the options compiled in are rvk\'s (an empty blob if asked for others - rvk/fsr2.cpp sets them).')
    parts.append('Fsr2ShaderBlobVK fsr2GetPermutationBlobByIndexVK(FfxFsr2Pass passId, uint32_t options)')
    parts.append('{')
    parts.append('    const uint32_t fixed = FSR2_SHADER_PERMUTATION_HDR_COLOR_INPUT | FSR2_SHADER_PERMUTATION_LOW_RES_MOTION_VECTORS |')
    parts.append('                           FSR2_SHADER_PERMUTATION_JITTER_MOTION_VECTORS | FSR2_SHADER_PERMUTATION_DEPTH_INVERTED;')
    parts.append('    if ((options & fixed) != FSR2_SHADER_PERMUTATION_LOW_RES_MOTION_VECTORS)')
    parts.append('        return {};')
    parts.append('    const bool lanczos = (options & FSR2_SHADER_PERMUTATION_REPROJECT_USE_LANCZOS_TYPE) != 0;')
    parts.append('    switch (passId) {')
    for pass_id, row in table:
        parts.append(f'    case {pass_id}: return lanczos ? {row[1]} : {row[0]};')
    parts.append('    default: return {};')
    parts.append('    }')
    parts.append('}')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(parts) + '\n')


main()
