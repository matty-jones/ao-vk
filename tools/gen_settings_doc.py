#!/usr/bin/env python3
"""docs/settings.md from the settings table (proxy/ddraw/rvk_settings.cpp): every setting, by section in the order
the settings window shows them, with its range, default, the feature switch it belongs to, whether the window shows
it, what it takes with RVK_Enhance off, and the names it had before.

Usage: tools/gen_settings_doc.py [--check]     (--check: exit 1 if docs/settings.md is out of date, write nothing)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "proxy", "ddraw", "rvk_settings.cpp")
RVK_H = os.path.join(ROOT, "rvk", "rvk.h")
OUT = os.path.join(ROOT, "docs", "settings.md")

STRING = r'"((?:[^"\\]|\\.)*)"'
ROW = re.compile(r'\{' + STRING + r',\s*' + STRING + r',\s*' + STRING + r',\s*(\w+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*'
                 r'([^,]+),\s*(nullptr|' + STRING + r'),\s*0(?:,\s*(nullptr|' + STRING + r'))?(?:,\s*' + STRING + r')?\}')
SKY_KEY = re.compile(r'RVK_SKY_KEY\(' + STRING + r',\s*' + STRING + r',\s*(\w+)\)')


def number(text):
    text = text.strip().rstrip("f")
    try:
        v = float(text)
    except ValueError:
        return None
    return v


def fmt(v, kind):
    if v is None:
        return "?"
    if kind == "Colour":
        return "%06X" % int(v)
    if kind == "Bool":
        return "on" if v else "off"
    return ("%g" % v)


def block(src, start, end="};"):
    a = src.index(start)
    return src[a:src.index(end, a)]


def main():
    src = open(SRC, encoding="utf-8").read()
    table = block(src, "Setting g_settings[] = {", "constexpr uint32_t kCount")
    header = open(RVK_H, encoding="utf-8").read()
    keys = re.search(r'enum SkyKey : uint32_t \{([^}]*)\}', header).group(1)
    refs = {k: i for i, k in enumerate(re.findall(r'kSky(\w+)', keys))}
    ref_values = re.search(r'kSkyKeyRef\[kSkyKeyCount\] = \{([^}]*)\}', open(RVK_H, encoding="utf-8").read())
    ref_values = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]+)', ref_values.group(1))] if ref_values else []

    settings = []
    for line in table.split("\n"):
        line = line.strip()
        m = SKY_KEY.match(line)
        if m:
            key = m.group(3)
            idx = refs.get(key[len("kSky"):], -1)
            settings.append(dict(name=m.group(1), label=m.group(2), section="Sky", type="Colour", min=0, max=0xFFFFFF,
                                 step=1, default=ref_values[idx] if 0 <= idx < len(ref_values) else None,
                                 env=None, parent="RVK_ProcSky", choices=None))
            continue
        m = ROW.match(line)
        if not m:
            continue
        settings.append(dict(name=m.group(1), label=m.group(2), section=m.group(3), type=m.group(4),
                             min=number(m.group(5)), max=number(m.group(6)), step=number(m.group(7)),
                             default=number(m.group(8)), env=m.group(10), parent=m.group(12), choices=m.group(13)))
    expected = len(re.findall(r'^\s*(\{"RVK_|RVK_SKY_KEY\(")', table, re.M))
    if len(settings) != expected:
        sys.exit(f"parsed {len(settings)} of {expected} settings - the table's format changed; fix ROW")

    hidden_list = set(re.findall(STRING, block(src, "const char* const kHidden[] = {")))
    always_on = set(re.findall(STRING, block(src, "const char* const kAlwaysOn[] = {", ";")))
    vanilla = {n: number(v) for n, v in re.findall(r'\{' + STRING + r',\s*([-0-9.f]+)\}', block(src, "const Vanilla kVanilla[] = {"))}
    migrations = re.findall(r'\{' + STRING + r',\s*' + STRING + r',\s*' + STRING + r',\s*([^}]+)\}',
                            block(src, "const Migration kMigrations[] = {"))
    was = {}
    for _, now, old, _ in migrations:
        if now != old:
            was.setdefault(now, []).append(old)
    by_name = {s["name"]: s for s in settings}
    knobs = set(re.findall(r'^\s*X\((\w+),', open(RVK_H, encoding="utf-8").read(), re.M))

    def hidden(s):
        if s["section"] == "Debug" or s["name"] in always_on or s["name"] in hidden_list:
            return True
        p = s["parent"]
        return bool(p and p not in always_on and p in by_name and hidden(by_name[p]))

    def value_range(s):
        if s["type"] == "Bool":
            return "on / off"
        if s["type"] == "Colour":
            return "RRGGBB"
        if s["type"] == "Choice" and s["choices"]:
            return " / ".join(s["choices"].split())
        return f"{fmt(s['min'], s['type'])} .. {fmt(s['max'], s['type'])}"

    sections = []
    for s in settings:
        if s["section"] not in sections:
            sections.append(s["section"])
    out = ["# Settings", "",
           "Generated by `tools/gen_settings_doc.py` from the settings table in `proxy/ddraw/rvk_settings.cpp` - don't edit",
           "by hand; run the script after changing a setting (`--check` tells whether this file is current).", "",
           "## How settings work", "",
           "- Every setting lives in `randy-vk.ini` next to `randy31.dll`, section `[Renderer]`. The file always lists every",
           "  setting; edits to it while the game runs take effect within half a second.",
           "- In game: AOReloaded's options window (the Renderer and Advanced tabs) shows the settings marked *window* below;",
           "  the console (the key left of 1) takes any setting by name, with or without `RVK_` (`darkness 1`, `bloom 0.5`).",
           "- `RVK_Enhance` off gives the game's own look: each setting takes its *game value* (below) while the stored values",
           "  stay. A feature's on / off switch (its *switch* below) does the same for the settings under it.",
           "- Presets (Original, Classic+, Modern, Ultra) set every setting outside General; Modern is the defaults.",
           "- A setting renamed or given a new default carries over once (`kMigrations`); its old names are listed.",
           "- *knob*: a plain value set through the generic path (`rvk.h` `RVK_FLOAT_KNOBS`, `RVK_BOOL_KNOBS`).", "",
           f"{len(settings)} settings, {sum(1 for s in settings if not hidden(s))} of them in the settings window.", ""]
    out.append("## Sections")
    out.append("")
    for sec in sections:
        n = sum(1 for s in settings if s["section"] == sec)
        out.append(f"- [{sec}](#{sec.lower().replace(' ', '-')}) ({n})")
    out.append("")
    for sec in sections:
        out += [f"## {sec}", "", "| Setting | What it does | Values | Default | Notes |", "| --- | --- | --- | --- | --- |"]
        for s in [x for x in settings if x["section"] == sec]:
            notes = []
            notes.append("ini only" if hidden(s) else "window")
            if s["parent"] and s["parent"] not in always_on:
                notes.append(f"switch `{s['parent']}`")
            if s["name"] in vanilla:
                notes.append(f"game value {fmt(vanilla[s['name']], s['type'])}")
            if s["name"][4:] in knobs:
                notes.append("knob")
            if s["env"]:
                notes.append(f"was env `{s['env']}`")
            if s["name"] in was:
                notes.append("was " + ", ".join(f"`{w}`" for w in was[s["name"]]))
            label = s["label"]
            # (A short label leans on its feature's switch above it in the window - "Strength": said here.)
            parent = by_name.get(s["parent"]) if s["parent"] and s["parent"] not in always_on else None
            if parent and len(label.split()) <= 4 and ":" not in label:
                label = f"{parent['label'].split(' (')[0]}: {label[0].lower() + label[1:]}"
            label = label.replace("|", "\\|")
            out.append(f"| `{s['name']}` | {label} | {value_range(s)} | {fmt(s['default'], s['type'])} | "
                       f"{'; '.join(notes)} |")
        out.append("")
    text = "\n".join(out)
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("docs/settings.md is out of date: run tools/gen_settings_doc.py")
            sys.exit(1)
        print("docs/settings.md is current")
        return
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}: {len(settings)} settings in {len(sections)} sections")


if __name__ == "__main__":
    main()
